package com.example.customer;

import java.math.BigDecimal;

/**
 * Calculates discounts for standard customers.
 */
public class StandardCustomerDiscountStrategy implements CustomerDiscountStrategy
{
	// ########################################################################
	// Constants
	// ########################################################################

	private static final BigDecimal DISCOUNT_RATE = BigDecimal.ZERO;

	// ########################################################################
	// Attributes
	// ########################################################################

	// ########################################################################
	// Accessors
	// ########################################################################

	// ########################################################################
	// Constructors
	// ########################################################################

	/**
	 * Creates the strategy.
	 */
	public StandardCustomerDiscountStrategy()
	{
	}

	// ########################################################################
	// Public Methods
	// ########################################################################

	@Override
	public BigDecimal calculateDiscount(final BigDecimal p_orderTotal)
	{
		BigDecimal discount = BigDecimal.ZERO;

		if (p_orderTotal != null)
		{
			discount = p_orderTotal.multiply(DISCOUNT_RATE);
		}

		return discount;
	}

	// ########################################################################
	// Protected Methods
	// ########################################################################

	// ########################################################################
	// Private Methods
	// ########################################################################

	// ########################################################################
	// Main
	// ########################################################################
}
